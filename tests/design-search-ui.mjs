/** Actual MBDyn candidates, GUI ranking, explicit Apply/Undo and project persistence. */
import './workspace-shim.mjs';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { once } from 'node:events';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const binary = process.env.MBDYN_DESIGN_TEST_SOLVER || 'verification/dependency-audit/ci-audit2-windows/solver/bin/mbdyn.exe';
const service = spawn('python', ['tests/design-search-server.py', binary], { windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
let diagnostics = '', browser;
const releaseGates = [];
service.stderr.on('data', data => { diagnostics += data; });
const lines = createInterface({ input: service.stdout });
const report = { scope: 'GUI with actual native MBDyn candidates and full CSV responses; sampled grid, no global optimality claim.', checks: [], errors: [], cases: [] };
const record = message => { report.checks.push(message); console.log(message); };
try {
  let timer;
  const ready = await Promise.race([once(lines, 'line').then(([line]) => JSON.parse(line)), once(service, 'exit').then(() => { throw Error(diagnostics); }), new Promise((_, reject) => { timer = setTimeout(() => reject(Error('Server startup timed out')), 15000); })]).finally(() => clearTimeout(timer));
  const base = `http://127.0.0.1:${ready.port}`;
  browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] });
  const page = await browser.newPage({ viewport: { width: 1480, height: 1100 }, acceptDownloads: true });
  page.on('pageerror', error => report.errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  await page.route('**/api/tour-preference', route => route.fulfill({ json: { enabled: false } }));
  const requests = [], completed = [];
  page.on('request', request => { if (request.url().endsWith('/api/run') && request.method() === 'POST') requests.push(request.postDataJSON()); });
  page.on('response', response => { if (response.url().endsWith('/api/run') && response.request().method() === 'POST') completed.push(response); });
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('#solverStatus')?.textContent.includes('MBDyn ready'));
  await page.locator('#projectFile').setInputFiles({ name: 'design.mbdyn-studio', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ format: 'mbdyn-studio/1', model: ready.model })) });
  await page.waitForFunction(() => document.querySelector('#documentName').textContent === 'Damped oscillator');
  await page.locator('#runButton').click();
  await page.waitForFunction(() => document.querySelector('#notice')?.textContent.includes('MBDyn completed successfully'));
  const originalRun = await page.locator('#runId').textContent();
  await page.locator('[data-step="simulate"]').click();
  await page.locator('#designSearchCard summary').click();
  await page.waitForFunction(() => document.querySelector('#designContext')?.textContent.includes('Responses from MBDyn run'));
  const config = name => page.locator(`#designSearchCard [data-config="${name}"]`);
  await config('input0').selectOption('parameters/damping'); await config('values0').fill('1, 4, 8');
  await config('input1').selectOption('parameters/mass'); await config('values1').fill('0.8, 1.2');
  await config('objective').selectOption(JSON.stringify(['global', 'x']));
  await config('constraint').selectOption(JSON.stringify(['global', 'velocity'])); await config('upper').fill('10');
  await page.locator('#designRun').click();
  await page.waitForFunction(() => document.querySelector('#designProgress')?.textContent.startsWith('Design search complete'), null, { timeout: 120000 });
  assert.equal(requests.length, 7); assert.equal(completed.length, 7);
  assert.equal(await page.locator('#designTable tbody tr').count(), 6);
  // Independently integrate the complete CSV; compare every displayed RMS and chosen case.
  for (let i = 1; i < completed.length; i++) {
    const solved = await completed[i].json(); assert.equal(solved.ok, true, solved.error);
    const csv = await (await page.request.get(base + solved.files.csv)).text();
    const rows = csv.trim().split(/\r?\n/).map(line => line.split(',')), header = rows.shift(), ti = header.indexOf('time'), xi = header.indexOf('x');
    assert(ti >= 0 && xi >= 0);
    const data = rows.map(row => [Number(row[ti]), Number(row[xi])]); let integral = 0;
    for (let j = 1; j < data.length; j++) integral += .5 * (data[j-1][1] ** 2 + data[j][1] ** 2) * (data[j][0] - data[j-1][0]);
    const rms = Math.sqrt(integral / (data.at(-1)[0] - data[0][0]));
    const displayed = Number(await page.locator('#designTable tbody tr').nth(i-1).locator('td').nth(3).textContent());
    assert(Math.abs(displayed-rms) < 1e-6);
    report.cases.push({ case: i, damping: requests[i].model.parameters.damping, mass: requests[i].model.parameters.mass, rms, runId: solved.runId, rows: data.length });
  }
  const winner = report.cases.reduce((a,b) => a.rms <= b.rms ? a : b);
  assert.match(await page.locator('#designSummary').textContent(), new RegExp(`case ${winner.case},`));
  assert.equal(winner.damping, 8);
  await mkdir('tests/evidence', { recursive: true });
  await page.locator('#designSearchCard').screenshot({ path: 'tests/evidence/design-search.png' });
  record('Six actual candidate runs match independently integrated full CSV RMS; all constraints and the sampled winner are displayed');
  const exportProject = async () => { const pending = page.waitForEvent('download'); await page.locator('#saveButton').click(); return JSON.parse(await readFile(await (await pending).path(), 'utf8')); };
  const original = await exportProject();
  assert.deepEqual(original.model, ready.model); assert.equal(await page.locator('#runId').textContent(), originalRun);
  assert.equal(original.view.designSearch.values0, '1, 4, 8');
  const csvDownload = page.waitForEvent('download'); await page.locator('#designCsv').click();
  assert.equal((await readFile(await (await csvDownload).path(), 'utf8')).trim().split('\n').length, 7);
  await page.locator('#designApply').click();
  const applied = await exportProject();
  assert.equal(applied.model.parameters.damping, winner.damping); assert.equal(applied.model.parameters.mass, winner.mass);
  assert.equal(applied.result.runId, original.result.runId); assert.equal(applied.result.csvText, original.result.csvText);
  assert(await page.locator('#designApply').isDisabled());
  await page.locator('#undoButton').click(); assert.deepEqual((await exportProject()).model, ready.model);
  await page.locator('#redoButton').click(); assert.deepEqual((await exportProject()).model, applied.model);
  record('Baseline/result CSV stay intact until explicit Apply; one Undo/Redo restores the evaluated inputs');
  await page.locator('#projectFile').setInputFiles({ name: 'saved.mbdyn-studio', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) });
  await page.waitForFunction(() => document.querySelector('#notice')?.textContent.includes('Project imported and validated'));
  await page.locator('[data-step="simulate"]').click();
  await page.locator('#designRefresh').click();
  await page.waitForFunction(() => document.querySelector('#designContext')?.textContent.includes('Responses from MBDyn run'));
  assert.equal(await config('values0').inputValue(), '1, 4, 8'); assert.equal(await config('values1').inputValue(), '0.8, 1.2');
  assert.equal(await config('objective').inputValue(), JSON.stringify(['global', 'x']));
  await config('values0').fill('1, 2, 3, 4, 5, 6'); await config('values1').fill('0.8, 0.9, 1, 1.1, 1.2, 1.3');
  await page.locator('#designRun').click();
  await page.waitForFunction(() => document.querySelector('#notice')?.textContent.includes('at most 25'));
  assert.equal(requests.length, 7);
  record('Project save/reopen retains search configuration; oversized grids fail before any solver call');
  await config('values0').fill('1, 4'); await config('values1').fill('0.8, 1.2');
  let release, entered; const gate = new Promise(resolve => { release = resolve; }), arrived = new Promise(resolve => { entered = resolve; });
  releaseGates.push(release);
  await page.route('**/api/run', async route => { entered(); await gate; await route.continue(); }, { times: 1 });
  await page.locator('#designRun').click(); await arrived;
  const cancel = page.waitForResponse(response => response.url().endsWith('/api/run/cancel'));
  await page.locator('#designCancel').click(); await cancel; release();
  await page.waitForFunction(() => document.querySelector('#designProgress')?.textContent.startsWith('Search stopped'), null, { timeout: 30000 });
  assert.equal(requests.length, 8); assert.equal(await page.locator('#designTable tbody tr').count(), 1); assert(await page.locator('#designApply').isDisabled());
  record('Stopping a pending real run cancels its token, stops later cases and prevents failed candidates being applied');
  // Keep a real CSV request unresolved through the production 30-second preparation deadline.
  let releaseCsv, csvEntered;
  const csvGate = new Promise(resolve => { releaseCsv = resolve; }), csvArrived = new Promise(resolve => { csvEntered = resolve; });
  releaseGates.push(releaseCsv);
  await page.route('**/results.csv', async route => { csvEntered(); await csvGate; await route.continue(); }, { times: 1 });
  await page.locator('#projectFile').setInputFiles({ name: 'csv-deadline.mbdyn-studio', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ format: 'mbdyn-studio/1', model: ready.model, view: { designSearch: original.view.designSearch } })) });
  await page.waitForFunction(() => document.querySelector('#notice')?.textContent.includes('Project imported and validated'));
  await page.locator('#runButton').click(); await csvArrived;
  await page.waitForFunction(() => document.querySelector('#notice')?.textContent.includes('MBDyn completed successfully'));
  await page.locator('#designRun').click();
  await page.waitForFunction(() => document.querySelector('#notice')?.textContent.includes('requires the complete solver CSV'), null, { timeout: 35000 });
  assert(await config('values0').isEnabled()); assert(await page.locator('#designRun').isEnabled());
  releaseCsv();
  record('A stalled full-CSV request reaches the real preparation deadline and releases the design controls');
  assert.deepEqual(report.errors, []);
  await mkdir('tests/evidence', { recursive: true });
  await page.screenshot({ path: 'tests/evidence/design-search-cancel.png' });
} finally {
  releaseGates.forEach(release => release());
  await mkdir('tests/evidence', { recursive: true });
  await writeFile('tests/evidence/design-search.json', JSON.stringify(report, null, 2));
  await browser?.close(); service.kill(); lines.close();
}
