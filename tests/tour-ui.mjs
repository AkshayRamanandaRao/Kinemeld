import './workspace-shim.mjs';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdir, writeFile} from 'node:fs/promises';
const base=process.env.MBDYN_STUDIO_URL || 'http://127.0.0.1:8768';
const browser=await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:960}}), errors=[];
const report={started:new Date().toISOString(),checks:[]};
page.on('pageerror',e=>errors.push(e.message));
try {
 const reset=await page.request.post(`${base}/api/tour-preference`,{data:{enabled:true}});assert(reset.ok());
 await page.goto(base);await page.waitForFunction(()=>document.querySelector('#solverStatus')?.textContent.includes('MBDyn ready'));
 await page.locator('#guidedTour').waitFor({state:'visible'});
 assert.match(await page.locator('#tourTitle').textContent(),/Welcome/);
 assert.equal(await page.locator('#tourButton').getAttribute('aria-expanded'),'true');
 await page.locator('#tourNext').click();
 assert.match(await page.locator('#tourText').textContent(),/STEP parts/);
 await page.locator('#stepButton').click();
 await page.waitForFunction(()=>document.querySelector('#guidedTour')?.parentElement?.id==='stepDialog');
 assert(await page.locator('#guidedTour').isVisible());
 await page.locator('#tourNext').click();
 assert.match(await page.locator('#tourTitle').textContent(),/Inspect the body/);
 await page.locator('#stepClose').click();
 await page.waitForFunction(()=>document.querySelector('#guidedTour')?.parentElement===document.body);
 assert(await page.locator('#guidedTour').isVisible());
 report.checks.push('Tour and STEP dialog remain visible and interactive together');
 await page.locator('#tourDisable').check();
 await page.locator('#tourClose').click();
 assert(await page.locator('#guidedTour').isHidden());
 await page.waitForFunction(async()=>!(await (await fetch('/api/tour-preference')).json()).enabled);
 await page.reload();await page.waitForFunction(()=>document.querySelector('#solverStatus')?.textContent.includes('MBDyn ready'));
 assert(await page.locator('#guidedTour').isHidden());
 await page.locator('#tourButton').click();assert(await page.locator('#guidedTour').isVisible());
 assert.equal(await page.locator('#tourDisable').isChecked(),true);
 await page.locator('#tourDisable').uncheck();await page.locator('#tourClose').click();
 await page.waitForFunction(async()=>(await (await fetch('/api/tour-preference')).json()).enabled);
 await page.reload();await page.waitForFunction(()=>document.querySelector('#solverStatus')?.textContent.includes('MBDyn ready'));
 assert(await page.locator('#guidedTour').isVisible());
 report.checks.push('Dismiss, persistent disable, manual reopen and reenable across reload');
 for(let i=0;i<5;i++) await page.locator('#tourNext').click();
 assert.match(await page.locator('#tourText').textContent(),/does not calculate mass, inertia, joints or contact/);
 await page.locator('#tourNext').click();assert.match(await page.locator('#tourText').textContent(),/validation pass alone does not prove/);
 await page.route('**/api/tour-preference',route=>route.request().method()==='POST' ? route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'unavailable'})}) : route.continue());
 await page.locator('#tourDisable').check();
 await page.waitForFunction(()=>document.querySelector('#notice')?.textContent.includes('tour preference could not be saved'));
 assert.match(await page.locator('#tourPreferenceStatus').textContent(),/could not be saved/);
 await page.locator('#tourClose').click();
 assert.match(await page.locator('#notice').textContent(),/could not be saved/);
 report.checks.push('A failed preference write is visible during and after the tour');
 assert.deepEqual(errors,[]);report.ok=true;
} catch(e){report.ok=false;report.failure=e.stack;process.exitCode=1;console.error(e);await page.screenshot({path:'tests/evidence/tour-ui-failure.png',fullPage:true}).catch(()=>{});}
finally{report.errors=errors;report.completed=new Date().toISOString();await mkdir('tests/evidence',{recursive:true});await writeFile('tests/evidence/tour-ui-verification.json',JSON.stringify(report,null,2));await browser.close();}
