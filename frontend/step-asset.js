const MAX_FILES = 24, MAX_BYTES = 12 * 1024 * 1024, MAX_TRIANGLES = 200000;
const digest = async bytes => [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))].map(b=>b.toString(16).padStart(2,'0')).join('');
/** Show product and occurrence names without using either as a binding identity. */
export function stepPartLabel(part) {
  return typeof part.productName==='string' && part.productName.trim() && part.productName!==(part.occurrenceName ?? part.name)
    ? `${part.productName} · ${part.name}` : part.name;
}
/** Flag bindings whose source has multiple generated occurrence indices. */
export function hasMultiPartBindings(asset) {
  if(!asset)return false;
  const counts=new Map();
  for(const part of asset.parts){const file=part.id.split(':',1)[0];counts.set(file,(counts.get(file)||0)+1);}
  return Object.keys(asset.metadata.bindings).some(id=>counts.get(id.split(':',1)[0])>1);
}
function base64(bytes) { let s=''; for (let i=0;i<bytes.length;i+=32768) s+=String.fromCharCode(...bytes.subarray(i,i+32768)); return btoa(s); }
function unbase64(s) { const raw=atob(s), bytes=new Uint8Array(raw.length); for(let i=0;i<raw.length;i++)bytes[i]=raw.charCodeAt(i);return bytes; }
function validWitness(w) {
  if(!w || typeof w!=='object' || Array.isArray(w))return false;
  if(w.scheme==='single-part/1')return Object.keys(w).length===1;
  return w.scheme==='step-nauo-id-path/1' && Object.keys(w).sort().join(',')==='path,scheme' && Array.isArray(w.path) && w.path.length>0 && w.path.length<=33 && w.path.every(s=>typeof s==='string' && s.trim() && s.length<=256 && !/[\x00-\x1f\x7f]/.test(s));
}
function validBinding(binding) {
  const pose=binding?.pose, keys=pose && typeof pose==='object' && !Array.isArray(pose) && Object.keys(pose).sort().join(',');
  return !!binding && typeof binding==='object' && !Array.isArray(binding) && !Object.keys(binding).some(k=>!['body','pose'].includes(k)) && typeof binding.body==='string' && binding.body.length<=32 && ['ry,x,y,z','rx,ry,rz,x,y,z'].includes(keys) && Object.values(pose).every(Number.isFinite);
}
function validId(id, fileCount) {
  const match=/^(0|[1-9][0-9]*):part-([1-9][0-9]*)$/.exec(id);
  return !!match && Number(match[1])<fileCount && Number(match[2])<=256;
}
function validateBindings(bindings, fileCount) {
  return !!bindings && typeof bindings==='object' && !Array.isArray(bindings) && Object.entries(bindings).every(([id,binding])=>validId(id,fileCount) && validBinding(binding));
}
const witnessKey = witness => JSON.stringify(witness.scheme==='single-part/1' ? [witness.scheme] : [witness.scheme,...witness.path]);

/** Preserve source STEP files; the render mesh is regenerated by the local CAD kernel. */
export async function loadStepAsset(files, bindings={}) {
  if (!Array.isArray(files) || !files.length || files.length>MAX_FILES) throw Error('Choose between 1 and 24 STEP files.');
  let total=0, triangles=0;
  const records=[], parts=[], occurrenceWitnesses={};
  for (let i=0;i<files.length;i++) {
    const item=files[i], name=item.name;
    if(typeof name!=='string' || !/\.(step|stp)$/i.test(name) || name.length>200) throw Error('Each source needs a valid STEP filename.');
    const bytes=item.bytes instanceof Uint8Array ? item.bytes : new Uint8Array(item.bytes);
    total+=bytes.length; if(!bytes.length || total>MAX_BYTES) throw Error('STEP sources together must be no larger than 12 MiB.');
    const hash=await digest(bytes);
    if(item.sha256 && hash!==item.sha256) throw Error(`STEP source ${name} failed its SHA-256 check.`);
    const response=await fetch('/api/step/convert',{method:'POST',headers:{'Content-Type':'application/step','X-Step-Filename':encodeURIComponent(name)},body:bytes});
    const converted=await response.json();
    if ([404,415].includes(response.status)) throw Error('STEP service is unavailable. Restart Kinemeld to load the updated backend.');
    if(!response.ok || !converted.ok) throw Error(converted.error || `Could not convert ${name}.`);
    if(converted.sha256!==hash || !Array.isArray(converted.parts) || !converted.parts.length) throw Error(`STEP conversion returned inconsistent data for ${name}.`);
    const witnesses=new Map();
    for(const part of converted.parts) {
      if(part.occurrenceWitness!=null && !validWitness(part.occurrenceWitness)) throw Error(`STEP conversion returned invalid occurrence identity for ${name}.`);
      if(part.occurrenceWitness) { const key=witnessKey(part.occurrenceWitness);witnesses.set(key,(witnesses.get(key)||0)+1); }
    }
    for(const part of converted.parts) {
      triangles+=part.indices.length/3;
      if(triangles>MAX_TRIANGLES) throw Error('STEP assembly exceeds the 200,000-triangle display limit.');
      const id=`${i}:${part.id}`, witness=part.occurrenceWitness;
      if(!validId(id,files.length) || parts.some(p=>p.id===id)) throw Error(`STEP conversion returned invalid occurrence IDs for ${name}.`);
      const verified=witness && witnesses.get(witnessKey(witness))===1 && (witness.scheme!=='single-part/1'||converted.parts.length===1) ? witness : null;
      if(verified) occurrenceWitnesses[id]=verified;
      parts.push({...part,id,occurrenceWitness:verified,occurrenceName:part.name,name:files.length>1?`${name} · ${part.name}`:part.name});
    }
    records.push({name,sha256:hash,byteLength:bytes.length,data:base64(bytes)});
  }
  const ids=new Set(parts.map(p=>p.id));
  if(!validateBindings(bindings,files.length) || Object.keys(bindings).some(id=>!ids.has(id))) throw Error('STEP part bindings are invalid.');
  return {metadata:{schemaVersion:1,format:'step',files:records,bindings:{...bindings},occurrenceWitnesses,unverifiedBindings:{}},parts,units:'m'};
}

/**
 * Add STEP files to a loaded set. Earlier parts keep their IDs, attachments and identities;
 * the new files follow them, and every part is labelled with its file as in a multi-file import.
 */
export async function appendStepAsset(previous, files) {
  const existing=previous.metadata.files;
  if(existing.length+files.length>MAX_FILES) throw Error('A STEP set holds at most 24 files.');
  const bytes=existing.reduce((sum,file)=>sum+file.byteLength,0)+files.reduce((sum,file)=>sum+(file.bytes.byteLength ?? file.bytes.length),0);
  if(bytes>MAX_BYTES) throw Error('STEP sources together must be no larger than 12 MiB.');
  const added=await loadStepAsset(files), offset=existing.length;
  if([...previous.parts,...added.parts].reduce((sum,part)=>sum+part.indices.length/3,0)>MAX_TRIANGLES) throw Error('STEP assembly exceeds the 200,000-triangle display limit.');
  const shift=id=>{const at=id.indexOf(':');return `${Number(id.slice(0,at))+offset}${id.slice(at)}`;};
  const records=[...existing,...added.metadata.files];
  const label=part=>`${records[Number(part.id.split(':',1)[0])].name} · ${part.occurrenceName ?? part.name}`;
  const parts=[...previous.parts,...added.parts.map(part=>({...part,id:shift(part.id)}))].map(part=>({...part,name:label(part)}));
  const witnesses=Object.fromEntries(Object.entries(added.metadata.occurrenceWitnesses).map(([id,witness])=>[shift(id),witness]));
  return {metadata:{...previous.metadata,files:records,bindings:{...previous.metadata.bindings},occurrenceWitnesses:{...previous.metadata.occurrenceWitnesses,...witnesses},unverifiedBindings:{...previous.metadata.unverifiedBindings}},parts,units:'m'};
}

export async function restoreStepAsset(asset) {
  if(!asset || asset.schemaVersion!==1 || asset.format!=='step' || !Array.isArray(asset.files) || !asset.files.length || asset.files.length>MAX_FILES || Object.keys(asset).some(k=>!['schemaVersion','format','files','bindings','occurrenceWitnesses','unverifiedBindings'].includes(k))) throw Error('Invalid saved STEP asset.');
  if(!validateBindings(asset.bindings,asset.files.length) || !validateBindings(asset.unverifiedBindings??{},asset.files.length)) throw Error('STEP part bindings are invalid.');
  const savedWitnesses=asset.occurrenceWitnesses??{};
  if(!savedWitnesses || typeof savedWitnesses!=='object' || Array.isArray(savedWitnesses) || Object.entries(savedWitnesses).some(([id,w])=>!validId(id,asset.files.length)||!validWitness(w))) throw Error('Saved STEP occurrence identities are invalid.');
  let total=0;
  const files=asset.files.map(file=>{
    if(!file || typeof file.data!=='string' || !/^(?:[A-Za-z0-9+/]{4})*(?:[A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(file.data) || !Number.isInteger(file.byteLength) || file.byteLength<1 || file.data.length!==Math.ceil(file.byteLength/3)*4 || !/^[0-9a-f]{64}$/.test(file.sha256 || '') || Object.keys(file).some(k=>!['name','sha256','byteLength','data'].includes(k))) throw Error('Invalid saved STEP source.');
    total+=file.byteLength;if(total>MAX_BYTES)throw Error('Saved STEP sources exceed 12 MiB.');
    const bytes=unbase64(file.data);if(bytes.length!==file.byteLength || base64(bytes)!==file.data)throw Error('Invalid STEP source encoding.');
    return {name:file.name,bytes,sha256:file.sha256};
  });
  const loaded=await loadStepAsset(files);
  const pending={...(asset.unverifiedBindings??{})}, active={};
  for(const [oldId,binding] of Object.entries(asset.bindings)) {
    const file=oldId.split(':',1)[0], witness=savedWitnesses[oldId];
    const fileParts=loaded.parts.filter(part=>part.id.split(':',1)[0]===file);
    let matches=[];
    if(witness) matches=fileParts.filter(part=>part.occurrenceWitness && witnessKey(part.occurrenceWitness)===witnessKey(witness));
    if(witness && matches.length!==1) throw Error(`STEP occurrence ${oldId} no longer matches its saved source identity. The project was not opened; review the source and original project.`);
    if(matches.length===1) {
      const id=matches[0].id;
      if(Object.hasOwn(active,id)) throw Error(`Saved STEP bindings resolve to the same occurrence ${id}.`);
      active[id]=binding;
    } else {
      if(Object.hasOwn(pending,oldId)) throw Error(`Saved STEP binding ${oldId} conflicts with an existing unverified binding.`);
      pending[oldId]=binding;
    }
  }
  loaded.metadata.bindings=active;
  loaded.metadata.unverifiedBindings=pending;
  return loaded;
}
